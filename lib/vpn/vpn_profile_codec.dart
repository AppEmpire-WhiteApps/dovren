import 'dart:convert';

import 'package:flutter_vless/flutter_vless.dart';
import 'package:flutter_vless/url/xray_config_model.dart';

/// Only accept a VLESS profile with the one local SOCKS listener consumed by
/// the packet tunnel. Metadata URLs must never be passed to the Xray engine.
class VpnProfileCodec {
  const VpnProfileCodec();

  /// Provisioning metadata must contain an actual usable VLESS profile.
  /// Missing or malformed fields are errors, never an HTTP URL fallback.
  ({String config, String country, String city}) decodeMetadata(Object? data) {
    if (data is! Map) {
      throw const FormatException(
        'Configuration response must be a JSON object.',
      );
    }
    // Imported configuration URLs can contain a base64 sing-box or Xray profile.
    final profile = _metadataProfile(data);
    if (profile is! String || profile.trim().isEmpty) {
      throw const FormatException('Response has no supported VLESS profile.');
    }
    return (
      config: normalize(profile),
      country:
          (data['countryCode'] is String ? data['countryCode'] as String : '')
              .trim()
              .toUpperCase(),
      city: (data['cityName'] is String ? data['cityName'] as String : '')
          .trim(),
    );
  }

  static final RegExp _uuid = RegExp(
    r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$',
  );

  String? _metadataProfile(Map data) {
    final singBox = data['base64Config'];
    if (singBox is String && singBox.trim().isNotEmpty) return singBox;

    final xray = data['base64Config_xray'];
    if (xray is String && xray.trim().isNotEmpty) return xray;

    return null;
  }

  String normalize(String payload) {
    final raw = payload.trim();
    if (raw.isEmpty || raw.length > 262144) {
      throw const FormatException('VLESS configuration is empty or too large.');
    }

    final String profile;
    if (raw.startsWith('{') || raw.startsWith('vless://')) {
      profile = raw;
    } else {
      try {
        profile = utf8.decode(base64.decode(base64.normalize(raw))).trim();
      } on FormatException {
        throw const FormatException(
          'Expected VLESS link, Xray JSON or base64 encoded profile.',
        );
      }
    }

    final supported = _singBoxToVless(profile) ?? profile;
    if (supported.startsWith('vless://')) {
      final authority = supported.substring(8).split(RegExp(r'[/?#]')).first;
      final explicitPort = RegExp(r':([0-9]+)$').firstMatch(authority);
      if (explicitPort != null) {
        final port = int.tryParse(explicitPort.group(1)!);
        if (port == null || port < 1 || port > 65535) {
          throw const FormatException('VLESS server port is invalid.');
        }
      }
    }
    try {
      final config = FlutterVless.parse(
        supported,
      ).getFullConfiguration(indent: 0);
      final decoded = jsonDecode(config) as Map<String, dynamic>;
      final inbounds = decoded['inbounds'];
      final outbounds = decoded['outbounds'];
      if (outbounds is! List || outbounds.isEmpty) {
        throw const FormatException(
          'A single loopback SOCKS inbound and VLESS outbound are required.',
        );
      }
      // An imported profile may supply only an Xray outbound. The iOS packet tunnel
      // still needs the plugin's canonical local SOCKS listener.
      if (supported.startsWith('{') &&
          (inbounds == null || (inbounds is List && inbounds.isEmpty))) {
        decoded['inbounds'] = [XrayInbound.localSocksTunnel().toJson()];
      }
      final listeners = decoded['inbounds'];
      if (listeners is! List || listeners.length != 1) {
        throw const FormatException(
          'A single loopback SOCKS inbound and VLESS outbound are required.',
        );
      }
      final inbound = listeners.single;
      final outbound = outbounds.first;
      if (inbound is! Map ||
          inbound['protocol'] != 'socks' ||
          inbound['listen'] != '127.0.0.1' ||
          inbound['port'] is! int ||
          (inbound['port'] as int) < 1 ||
          (inbound['port'] as int) > 65535 ||
          outbound is! Map ||
          outbound['protocol'] != 'vless') {
        throw const FormatException(
          'Only a local SOCKS inbound with a VLESS outbound is supported.',
        );
      }
      // Downloaded Xray profiles retain their explicit routing. Share links
      // use only the proxy and blackhole routes generated by the parser.
      final generatedLink = !supported.startsWith('{');
      if (generatedLink) {
        final keptOutbounds = outbounds
            .where((entry) => entry is! Map || entry['protocol'] != 'freedom')
            .toList();
        decoded['outbounds'] = keptOutbounds;
        final tag = outbound['tag'];
        final proxyTag = tag is String && tag.isNotEmpty ? tag : null;
        final routing = decoded['routing'];
        if (routing != null && routing is! Map) {
          throw const FormatException('Unsupported Xray routing.');
        }
        final rules = routing is Map ? routing['rules'] : null;
        final balancers = routing is Map ? routing['balancers'] : null;
        if ((rules != null && rules is! List) ||
            (balancers != null &&
                (balancers is! List || balancers.isNotEmpty)) ||
            (rules is List &&
                rules.any(
                  (rule) =>
                      rule is! Map ||
                      rule.containsKey('balancerTag') ||
                      (rule['outboundTag'] != 'blackhole' &&
                          (proxyTag == null ||
                              rule['outboundTag'] != proxyTag)),
                )) ||
            rules is List && rules.isNotEmpty ||
            outbound['proxySettings'] != null ||
            keptOutbounds
                .skip(1)
                .any(
                  (entry) => entry is! Map || entry['protocol'] != 'blackhole',
                )) {
          throw const FormatException(
            'VPN routing must use only the VLESS proxy or blackhole.',
          );
        }
      }
      final settings = outbound['settings'];
      final servers = settings is Map ? settings['vnext'] : null;
      final server = servers is List && servers.isNotEmpty
          ? servers.first
          : null;
      final users = server is Map ? server['users'] : null;
      final user = users is List && users.isNotEmpty ? users.first : null;
      if (server is! Map ||
          server['address'] is! String ||
          (server['address'] as String).isEmpty ||
          server['port'] is! int ||
          (server['port'] as int) < 1 ||
          (server['port'] as int) > 65535 ||
          user is! Map ||
          user['id'] is! String ||
          !_uuid.hasMatch(user['id'] as String)) {
        throw const FormatException(
          'VLESS server address, port or client ID is invalid.',
        );
      }
      return jsonEncode(decoded);
    } on FormatException {
      rethrow;
    } catch (_) {
      throw const FormatException('Invalid VLESS configuration.');
    }
  }

  /// Converts a supported sing-box VLESS outbound into the native profile.
  /// Direct routes are discarded; the packet tunnel supplies the local SOCKS
  /// inbound instead of the profile's TUN inbound.
  String? _singBoxToVless(String profile) {
    if (!profile.startsWith('{')) return null;
    final decoded = jsonDecode(profile);
    if (decoded is! Map) return null;
    final outbounds = decoded['outbounds'];
    if (outbounds is! List) {
      throw const FormatException('Unsupported sing-box VLESS profile.');
    }
    Map<dynamic, dynamic>? outbound;
    for (final entry in outbounds) {
      if (entry is Map && entry['type'] == 'vless') {
        if (outbound != null) {
          throw const FormatException('Use one VLESS outbound per profile.');
        }
        outbound = entry;
      }
    }
    if (outbound == null || outbound.containsKey('protocol')) return null;

    final host = outbound['server'];
    final port = outbound['server_port'];
    final id = outbound['uuid'];
    if (host is! String ||
        host.isEmpty ||
        port is! int ||
        id is! String ||
        !_uuid.hasMatch(id)) {
      throw const FormatException('Unsupported sing-box VLESS profile.');
    }

    final transport = outbound['transport'];
    if (transport != null) {
      const names = {
        'tcp': 'tcp',
        'raw': 'raw',
        'ws': 'websocket',
        'websocket': 'websocket',
        'http': 'http',
        'h2': 'http',
        'grpc': 'grpc',
        'quic': 'quic',
        'xhttp': 'xhttp',
        'httpupgrade': 'httpupgrade',
        'http_upgrade': 'httpupgrade',
        'kcp': 'mkcp',
        'mkcp': 'mkcp',
      };
      final type = transport is Map ? transport['type'] : null;
      if (type is! String || !names.containsKey(type.toLowerCase())) {
        throw const FormatException('Unsupported sing-box transport.');
      }
      outbound['transport'] = {
        ...transport as Map,
        'type': names[type.toLowerCase()],
      };
    }
    try {
      // Use the pinned parser's transport/TLS mapping instead of dropping WS,
      // gRPC, Reality fingerprints or VLESS encryption during conversion.
      return FlutterVless.parse(
        jsonEncode({
          'outbounds': [outbound],
        }),
      ).url;
    } catch (_) {
      throw const FormatException('Unsupported sing-box VLESS profile.');
    }
  }
}
